const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const data = new Map();
const storage = { getItem: k => data.get(k) || null, setItem: (k,v) => data.set(k,String(v)), removeItem: k => data.delete(k) };
const ctx = { window: {}, localStorage: storage, sessionStorage: storage, Date, Math, console };
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(__dirname,'../js/app.js'),'utf8'),ctx);
const VZ = ctx.window.VZ;
const p = VZ.products()[0];
assert.ok(p);
const batchCount = VZ.db.batches.filter(b => b.productId === p.id).length;
assert.equal(VZ.login('staff1','staff123').ok,true);
assert.equal(VZ.restoreProduct(p.id).ok,false,'staff cannot restore');
assert.equal(VZ.login('admin','admin123').ok,true);
assert.equal(VZ.archiveProduct(p.id).ok,true);
assert.equal(VZ.products().some(x => x.id === p.id),false);
assert.equal(VZ.products(true).some(x => x.id === p.id),true);
assert.equal(VZ.restoreProduct(p.id).ok,true);
assert.equal(VZ.products().some(x => x.id === p.id),true);
assert.equal(VZ.restoreProduct(p.id).ok,false,'cannot restore twice');
assert.equal(VZ.db.batches.filter(b => b.productId === p.id).length,batchCount,'preserve batches');
assert.ok(VZ.db.audit.some(a => a.action === 'inventory.restore' && a.target === p.name));
console.log('PASS: archive, restore, staff restriction, duplicate restore, batches and audit log.');
