'use strict';
const fs = require('node:fs'), vm = require('node:vm'), assert = require('node:assert/strict');
const memory = new Map();
const store = { getItem: k => memory.get(k) || null, setItem: (k,v) => memory.set(k, String(v)), removeItem: k => memory.delete(k) };
const ctx = { window: {}, localStorage: store, sessionStorage: store, Date, Math, console };
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(require('node:path').join(__dirname, '../js/app.js'), 'utf8'), ctx);
const VZ = ctx.window.VZ;
assert.ok(VZ.db.users.every(u => /^(ADM|STF)-\d{4,}$/.test(u.displayId) && u.displayId.startsWith(u.role === 'admin' ? 'ADM-' : 'STF-')));
assert.ok(VZ.db.products.every(p => /^ITM-\d{4,}$/.test(p.displayId)));
assert.equal(new Set(VZ.db.users.map(u => u.displayId)).size, VZ.db.users.length);
assert.equal(new Set(VZ.db.products.map(p => p.displayId)).size, VZ.db.products.length);
const pet = VZ.db.pets[0];
assert.equal(VZ.login('staff1','staff123').ok, true);
const result = VZ.requestPetDeath(pet.id, { date: VZ.today(), location: 'At clinic', notes: 'Confirmed by clinic staff.' });
assert.equal(result.ok, true);
assert.notEqual(pet.status, 'Deceased');
assert.equal(VZ.requestPetDeath(pet.id, { date: VZ.today(), location: 'At clinic' }).ok, false, 'duplicate blocked');
assert.equal(VZ.reviewPetDeath(result.request.id, 'approve', '').ok, false, 'staff cannot approve');
assert.equal(VZ.petDeathRequests('pending').length, 1);
assert.equal(VZ.login('admin','admin123').ok, true);
assert.equal(VZ.pendingApprovalCount() > 0, true);
assert.equal(VZ.reviewPetDeath(result.request.id, 'approve', '').ok, true);
assert.equal(pet.status, 'Deceased');
assert.equal(VZ.petState(pet).dueItems.length, 0);
assert.equal(VZ.reviewPetDeath(result.request.id, 'approve', '').ok, false, 'cannot approve twice');
assert.equal(VZ.setPetStatus(pet.id, 'Healthy').ok, false, 'cannot silently reactivate');
const other = VZ.db.pets[1];
assert.equal(VZ.login('staff1','staff123').ok, true);
const second = VZ.requestPetDeath(other.id, { date: VZ.today(), location: 'Outside clinic', notes: '' });
assert.equal(second.ok, true);
assert.equal(VZ.login('admin','admin123').ok, true);
assert.equal(VZ.reviewPetDeath(second.request.id, 'reject', '').ok, false, 'reject requires note');
assert.equal(VZ.reviewPetDeath(second.request.id, 'reject', 'Insufficient confirmation').ok, true);
assert.notEqual(other.status, 'Deceased');
assert.ok(VZ.db.audit.some(a => a.action === 'pet.deceased.approved'));
console.log('PASS: unique staff/item IDs, pending request, staff restriction, approval, rejection, duplicate guard, audit, reminder suppression.');
