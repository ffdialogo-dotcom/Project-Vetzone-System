assert.equal(pet.deceased.notes, 'Confirmed by admin'); assert.equal(V.petDeathRequests('pending').length, 0);
assert.equal(JSON.stringify(V.db.records), history); assert.equal(V.petState(pet).dueItems.length, 0);
